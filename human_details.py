"""Section 18's items "reported without a hypothesis", written to
results_human/DETAILS.md:

- every period error, and every exclusion question the cue list missed;
- per-field agreement of each vendor's full signature with the reference;
- every wrong reuse by split_template_fullsig, with its cause;
- results per writer;
- the shortlist floor sweep.

Reads the saved extractions and the vectors human_eval.py cached, so no model
is loaded. The full-signature routing is rebuilt as evaluate.cache_simulation
builds it, and checked against each report's own counts before use.

  python human_details.py
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from domains import DOMAINS
from evaluate import embed, slug
from guards import (
    GOLD_FULL_SIGNATURES,
    full_signature_key,
    has_negation_cue,
    negation_consistent,
)
from human_eval import DOMAIN_NAMES, args_for, label, load

HERE = Path(__file__).parent
R = HERE / "results_human"
FLOOR = 0.50
RUNS = ("r1", "r2", "r3")
EMBEDDERS = (
    ("st:sentence-transformers/all-MiniLM-L6-v2", ""),
    ("st:sentence-transformers/all-mpnet-base-v2", ""),
    ("st:BAAI/bge-base-en-v1.5", ""),
    ("st:intfloat/e5-base-v2", "query: "),
)
RELFULL = {
    "gemini": "gemini-relfull_gemini-3.1-flash-lite",
    "openai": "openai-relfull_gpt-6-luna",
}
FIELDS = ("operation", "measure", "group_by", "excludes")


def ns(emb: str, prefix: str, d: str):
    import argparse

    return argparse.Namespace(
        embedder=emb, prefix=prefix, task_type=None, project="", location="", domain=d
    )


def read_ext(path: Path) -> dict[str, dict]:
    with path.open(encoding="utf-8") as f:
        return {r["id"]: r for r in map(json.loads, f)}


def fullsig_routes(d: str, qs: list[dict], ext: dict, emb: str, prefix: str) -> list[dict]:
    """One row per writer's question: reused or not, and if so to what."""
    a = ns(emb, prefix, d)
    texts = sorted({q["text"] for q in qs} | {ext[q["id"]]["masked_text"] for q in qs})
    ti = {t: i for i, t in enumerate(texts)}
    v = embed(texts, args_for(a), R / d / slug(label(a)))
    anchors = [q for q in qs if q["is_anchor"]]
    queries = [q for q in qs if not q["is_anchor"]]
    va = v[[ti[ext[q["id"]]["masked_text"]] for q in anchors]]
    vq = v[[ti[ext[q["id"]]["masked_text"]] for q in queries]]
    S = vq @ va.T

    def slots(q):
        return sorted(ext[q["id"]]["params"])

    def cue_ok(q):
        return negation_consistent(q["text"], ext[q["id"]]["params"])

    sa = [full_signature_key(ext[q["id"]].get("signature")) for q in anchors]
    rows = []
    for i, q in enumerate(queries):
        sq = full_signature_key(ext[q["id"]].get("signature"))
        cue = has_negation_cue(q["text"])
        elig = np.array(
            [
                slots(q) == slots(x)
                and cue == has_negation_cue(x["text"])
                and cue_ok(q)
                and cue_ok(x)
                and sq is not None
                and sq == sa[j]
                for j, x in enumerate(anchors)
            ]
        )
        M = np.where(elig, S[i], -np.inf)
        j = int(M.argmax())
        reused = bool(np.isfinite(M[j]) and M[j] >= FLOOR)
        values_ok = all(ext[q["id"]]["params"].get(s) == q["params"][s] for s in q["slots"])
        same_intent = anchors[j]["intent"] == q["intent"]
        rows.append(
            {
                "q": q,
                "reused": reused,
                "ok": reused and same_intent and values_ok,
                "anchor": anchors[j],
                "cause": None
                if not reused or (same_intent and values_ok)
                else "template and values"
                if not same_intent and not values_ok
                else "template"
                if not same_intent
                else "values",
            }
        )
    return rows


def main() -> None:
    qs = {d: load(HERE / "data_human", d, None) for d in DOMAIN_NAMES}
    human = {d: [q for q in qs[d] if not q["is_anchor"]] for d in DOMAIN_NAMES}
    out = [
        "# Human-written questions: details (README sections 18 and 21)",
        "",
        "Generated by `human_details.py` from the saved extractions. Registered",
        "runs unless a table says `-yearfix` (section 20, exploratory).",
        "",
    ]

    # Period errors, registered relfull runs.
    out += [
        "## Every period error (relfull, r1-r3)",
        "",
        "| Domain | Id | Question | Gold | Gemini | OpenAI |",
        "|---|---|---|---|---|---|",
    ]
    for d in DOMAIN_NAMES:
        got = defaultdict(lambda: defaultdict(Counter))
        for v, arm in RELFULL.items():
            for t in RUNS:
                ext = read_ext(R / d / "extraction" / f"{arm}_{t}" / "extracted.jsonl")
                for q in human[d]:
                    e = ext[q["id"]]
                    p = e["params"].get("period")
                    if p != q["params"]["period"]:
                        why = "no year" if "'year': None" in (e.get("note") or "") else str(p)
                        got[q["id"]][v][why] += 1
        for q in human[d]:
            if q["id"] in got:
                cell = {
                    v: ", ".join(f"{k} ×{n}" for k, n in got[q["id"]][v].items()) or "—"
                    for v in RELFULL
                }
                text = q["text"].replace("|", "/")
                out.append(
                    f"| {d} | {q['id']} | {text} | {q['params']['period']} "
                    f"| {cell['gemini']} | {cell['openai']} |"
                )
    out += ["", '"no year" is section 20\'s resolver defect: the row has no period.', ""]

    # Missed exclusions.
    out += ["## Exclusion questions the cue list missed", ""]
    for d in DOMAIN_NAMES:
        excl = {n[0] for n in DOMAINS[d].negations}
        for q in human[d]:
            if q["intent"] in excl and not has_negation_cue(q["text"]):
                out.append(f"- {d} {q['id']}: {q['text']}")
    out.append("")

    # Signature agreement per field.
    out += [
        "## Full-signature agreement with the reference (writers' questions, mean of r1-r3)",
        "",
        "| Vendor | Domain | " + " | ".join(FIELDS) + " | all four |",
        "|---|---|" + "---|" * (len(FIELDS) + 1),
    ]
    for v, arm in RELFULL.items():
        for d in DOMAIN_NAMES:
            hits, n = Counter(), 0
            for t in RUNS:
                ext = read_ext(R / d / "extraction" / f"{arm}_{t}" / "extracted.jsonl")
                for q in human[d]:
                    gold = dict(zip(FIELDS, GOLD_FULL_SIGNATURES[d][q["intent"]], strict=True))
                    sig = ext[q["id"]].get("signature") or {}
                    ok = [sig.get(f) == gold[f] for f in FIELDS]
                    for f, o in zip(FIELDS, ok, strict=True):
                        hits[f] += o
                    hits["all"] += all(ok)
                    n += 1
            cells = " | ".join(f"{hits[f] / n:.3f}" for f in (*FIELDS, "all"))
            out.append(f"| {v} | {d} | {cells} |")
    out.append("")

    # Wrong reuses and per-writer results, from the rebuilt routing.
    wrong = defaultdict(list)
    writer = defaultdict(lambda: Counter())
    for tagset, vendors in (("", ("gemini", "openai")), ("-yearfix", ("openai",))):
        for v in vendors:
            for d in DOMAIN_NAMES:
                for t in RUNS:
                    run = R / d / "extraction" / f"{RELFULL[v]}_{t}{tagset}"
                    ext = read_ext(run / "extracted.jsonl")
                    for emb, prefix in EMBEDDERS:
                        rows = fullsig_routes(d, qs[d], ext, emb, prefix)
                        rep = json.loads(
                            (run / slug(label(ns(emb, prefix, d))) / "report.json").read_text(
                                encoding="utf-8"
                            )
                        )
                        cal = rep["cache"]["calibrated"]["split_template_fullsig"]
                        des = rep["cache"]["designs"]["split_template_fullsig"]
                        n_ok = sum(r["ok"] for r in rows)
                        n_bad = sum(r["reused"] and not r["ok"] for r in rows)
                        want = round(des["calibrated_correct_reuse"]["value"] * len(rows))
                        if n_bad != cal["false_reuses"] or n_ok != want:
                            raise SystemExit(f"routing disagrees with {run.name} {emb} {d}")
                        for r in rows:
                            if r["reused"] and not r["ok"]:
                                wrong[(v + tagset, d, r["q"]["id"])].append(
                                    (t, emb.split("/")[-1], r["cause"], r["anchor"]["intent"])
                                )
                            if not tagset:
                                k = (v, r["q"]["writer"])
                                writer[k]["n"] += 1
                                writer[k]["ok"] += r["ok"]
                                writer[k]["wrong"] += r["reused"] and not r["ok"]
    out += [
        "## Every wrong reuse by split_template_fullsig (relfull, floor 0.50)",
        "",
        "Counted over 3 runs × 4 embedders = 12 cells per question. The routing was",
        "rebuilt and matched each report's false-reuse and correct-reuse counts.",
        "",
        "| Runs | Domain | Id | Question | Cause | Reused for | Cells |",
        "|---|---|---|---|---|---|---|",
    ]
    for (v, d, qid), hits in sorted(wrong.items()):
        q = next(x for x in human[d] if x["id"] == qid)
        causes = ", ".join(sorted({h[2] for h in hits}))
        intents = ", ".join(sorted({h[3] for h in hits}))
        text = q["text"].replace("|", "/")
        out.append(
            f"| {v} | {d} | {qid} | {text} ({q['intent']}) | {causes} | {intents} | {len(hits)} |"
        )
    out += [
        "",
        "## Per writer (registered relfull runs, split_template_fullsig at 0.50)",
        "",
        "Pooled over domains, runs and the four embedders.",
        "",
        "| Vendor | Writer | Questions × cells | Correct reuse | Wrong reuses (share of reuses) |",
        "|---|---|---|---|---|",
    ]
    for (v, w), c in sorted(writer.items()):
        n_re = c["ok"] + c["wrong"]
        out.append(
            f"| {v} | {w} | {c['n']} | {c['ok'] / c['n']:.3f} | "
            f"{c['wrong']} ({c['wrong'] / n_re:.3f}) |"
        )
    out.append("")

    # Floor sweep.
    out += [
        "## Shortlist floor sweep (registered relfull runs)",
        "",
        "Correct reuse, and wrong reuses, as min-max over 3 runs × 4 embedders.",
        "",
        "| Vendor | Domain | Design | "
        + " | ".join(["none", "0.3", "0.4", "0.5", "0.6", "0.7"])
        + " |",
        "|---|---|---|" + "---|" * 6,
    ]
    for v, arm in RELFULL.items():
        for d in DOMAIN_NAMES:
            for design in ("split_template_fullsig", "split_template_fullsig_gold"):
                cols = defaultdict(list)
                for t in RUNS:
                    for emb, prefix in EMBEDDERS:
                        p = R / d / "extraction" / f"{arm}_{t}" / slug(label(ns(emb, prefix, d)))
                        rep = json.loads((p / "report.json").read_text(encoding="utf-8"))
                        for row in rep["cache"]["shortlist_sweep"][design]:
                            cols[row["floor"]].append(row)
                cells = []
                for f in (None, 0.3, 0.4, 0.5, 0.6, 0.7):
                    c = [r["correct_reuse_rate"] for r in cols[f]]
                    w = [r["false_reuses"] for r in cols[f]]
                    cells.append(f"{min(c):.2f}–{max(c):.2f} / {min(w)}–{max(w)}")
                name = "fullsig" if design.endswith("fullsig") else "reference"
                out.append(f"| {v} | {d} | {name} | " + " | ".join(cells) + " |")
    out.append("")

    (R / "DETAILS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {R / 'DETAILS.md'}")


if __name__ == "__main__":
    main()
